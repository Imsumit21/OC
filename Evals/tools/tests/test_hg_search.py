import base64
import importlib.util
import io
import json
from pathlib import Path
import sys
from types import SimpleNamespace
import tempfile
import unittest
from unittest.mock import patch
from contextlib import redirect_stdout

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
spec = importlib.util.spec_from_file_location('hg_search', Path(__file__).resolve().parents[1] / 'hg_search.py')
h = importlib.util.module_from_spec(spec)
spec.loader.exec_module(h)


class SearchTests(unittest.TestCase):
    def test_inventory_uses_refreshed_coverage_instead_of_service_names(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            refs = root / 'Evals/references'
            refs.mkdir(parents=True)
            services = {}
            for service, empty in [('gcal', False), ('gslides', False), ('contacts', True), ('github', None)]:
                info = {'path': 'Base/' + service, 'file_count': 1, 'total_bytes': 2}
                if empty is not None:
                    info['empty_export'] = empty
                services[service] = info
            (refs / 'universe_manifest.json').write_text(json.dumps({
                'archive': 'refreshed.zip', 'archive_sha256': 'fixture', 'services': services}))
            output = io.StringIO()
            with patch.object(h, 'ROOT', root), patch.object(sys, 'argv', ['hg_search.py', 'inventory']), redirect_stdout(output):
                self.assertEqual(h.main(), 0)
            result = json.loads(output.getvalue())
            self.assertEqual({r['service']: r['empty_export'] for r in result['services']},
                             {'gcal': False, 'gslides': False, 'contacts': True, 'github': None})
            self.assertFalse(result['individual_files_verified'])

    def test_stream_matches_standard_json_at_chunk_boundaries(self):
        # Use valid escaped JSON generated by the standard encoder.
        source = json.dumps({'a/b~c': [1.234e-15, -12.5, 2e12, True, False, None, '€ and "quoted"'], 'empty': {}, 'array': []})
        for size in range(1, 21):
            stream = h.Stream(io.StringIO(source), chunk=size)
            it = stream.events()
            output = ''.join(h.render_subtree(next(it), it))
            self.assertEqual(json.loads(output), json.loads(source))
            self.assertEqual(stream.peek(), '')
        self.assertEqual(h.parse_pointer(h.pointer(('a/b~c', '0'))), ('a/b~c', '0'))

    def test_invalid_and_truncated_json(self):
        for source in ['{"x":[1,2}', '{"x":1e}', '[true,]', '{"x":"unterminated']:
            with self.assertRaises(ValueError):
                list(h.Stream(io.StringIO(source), chunk=2).events())

    def test_search_get_coverage_and_decoding(self):
        old_root = h.ROOT
        with tempfile.TemporaryDirectory() as tmp:
            h.ROOT = Path(tmp).resolve()
            try:
                refs = h.ROOT / 'Evals/references'
                refs.mkdir(parents=True)
                folder = h.ROOT / 'Base/gmail'
                folder.mkdir(parents=True)
                body = 'Secret needle café ' + 'long text ' * 100
                data = {'messages': [{'id': 'm1', 'payload': {'body': {'data': base64.urlsafe_b64encode(body.encode()).decode()}}}], 'a/b~c': [7]}
                (folder/'thread.json').write_text(json.dumps(data))
                records = [{'path': 'thread.json', 'bytes': 1}]
                (folder/'source_manifest.json').write_text(json.dumps({'files': records}))
                (refs/'universe_manifest.json').write_text(json.dumps({'services': {'gmail': {'path': 'Base/gmail'}}}))
                args = SimpleNamespace(service='gmail', query='needle', file=None, pointer='', key=None, case_sensitive=False, limit=20)
                found = h.search(args)
                self.assertTrue(found['scan_complete'])
                self.assertEqual(len(found['matches']), 1)
                self.assertEqual(found['matches'][0]['encoding'], 'base64url-utf8')
                args.limit = 1
                self.assertFalse(h.search(args)['scan_complete'])
                args.query = 'absent'
                self.assertTrue(h.search(args)['scan_complete'])
                read = SimpleNamespace(service='gmail', file='thread.json', pointer='/messages/0', offset=0, max_chars=53, decode_base64=False)
                chunks = []
                while True:
                    result = h.get(read)
                    chunks.append(result['text'])
                    if not result['truncated']:
                        break
                    read.offset = result['next_offset']
                self.assertEqual(json.loads(''.join(chunks)), data['messages'][0])
                read.pointer = '/messages/0/payload/body/data'
                read.offset, read.max_chars, read.decode_base64 = 0, 20000, True
                self.assertEqual(h.get(read)['text'], body)
                read.decode_base64, read.pointer = False, '/a~1b~0c/0'
                self.assertEqual(json.loads(h.get(read)['text']), 7)
                read.file = '../outside.json'
                with self.assertRaises(ValueError):
                    h.get(read)
                (folder/'thread.json').write_text('{invalid')
                self.assertFalse(h.search(args)['scan_complete'])
                self.assertTrue(h.search(args)['errors'])
                (folder/'thread.json').unlink()
                self.assertTrue(h.search(args)['errors'])
            finally:
                h.ROOT = old_root


if __name__ == '__main__':
    unittest.main()
