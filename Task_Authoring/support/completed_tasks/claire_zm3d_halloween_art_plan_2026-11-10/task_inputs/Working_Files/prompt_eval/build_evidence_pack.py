CHANNELS = {c["id"]: c for c in json.load(open(SLACK / "channels.json"))}


def slack_msg(ch, ts, with_thread=True):
    for f in sorted(glob.glob(str(SLACK / "messages" / ch / "*.json"))):
        d = json.load(open(f))
        for i, x in enumerate(d):
            if x.get("ts") == ts:
                rel = Path(f).relative_to(OS).as_posix()
                files = [y.get("name") for y in x.get("files") or []]
                A(f"- `{ch}/{ts}` ({utc(ts)}, {USERS.get(x.get('user'), x.get('user'))} `{x.get('user')}`) — `{rel}#/{i}`"
                  f" reply_count {x.get('reply_count')}{' files ' + str(files) if files else ''}")
                text = x.get("text") or ""
                for a in x.get("attachments") or []:
                    text += " | " + (a.get("fallback") or a.get("text") or "")
                A(f"  > {q(text, 700)}")
                if with_thread:
                    for j, y in enumerate(d):
                        if y.get("thread_ts") == ts and y.get("ts") != ts:
                            A(f"  - reply `{ch}/{y['ts']}` ({utc(y['ts'])}, {USERS.get(y.get('user'), y.get('user'))}) `#/{j}`: "
                              f"{q(y.get('text'), 400)}" + (f" files {[z.get('name') for z in y.get('files') or []]}" if y.get("files") else ""))
                return
    A(f"- `{ch}/{ts}`: NOT FOUND in base")


def build_posts(numbers):
    """#builds (C05433XK267) job-result posts naming each build number."""
    hits = {n: [] for n in numbers}
    for f in sorted(glob.glob(str(SLACK / "messages" / "C05433XK267" / "*.json"))):
        d = json.load(open(f))
        for i, x in enumerate(d):
            t = (x.get("text") or "") + " ".join((a.get("fallback") or a.get("text") or "") for a in x.get("attachments") or [])
            for n in numbers:
                if re.search(rf"(?:Match3D Android|Match 3D iOS Internal|Match3D iOS) - #{n}\b[^\n]*", t):
                    m = re.search(rf"((?:Match3D Android|Match 3D iOS Internal|Match3D iOS) - #{n}\b[^\n]*)", t)
                    hits[n].append(f"`C05433XK267/{x['ts']}` ({utc(x['ts'])}) `{Path(f).relative_to(OS).as_posix()}#/{i}`: {q(m.group(1), 160)}")
    return hits


