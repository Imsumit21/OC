def utc(ts):
    return dt.datetime.fromtimestamp(float(ts), dt.timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")


def q(s, n=None):
    s = (s or "").replace("\r", "")
    return s if n is None or len(s) <= n else s[:n] + " …"


