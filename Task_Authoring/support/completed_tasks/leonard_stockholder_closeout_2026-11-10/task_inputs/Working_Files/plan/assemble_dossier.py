def g1(section):
    t = rd("g1_grounding.md", os.path.join(WF, "research"))
    m = re.search(rf"^## {re.escape(section)}.*?$(.*?)(?=^## |\Z)", t, re.S | re.M)
    if not m:
        return f"({section} not produced yet)"
    lines = [x.replace("[]", "(none)").replace("<name>", "(name)") for x in m.group(1).strip().splitlines()]
    if not section.startswith("1.D"):
        return "\n".join(lines)
    out, i = [], 0                   # 1.D: only rows with a record locator stay evidence items; noise and zero-hit rows become prose
    while i < len(lines):
        line = lines[i]
        if line.startswith("- ") and not RX_PTR.search(line):
            out.append(line[2:])
            i += 1
        elif line.startswith("|"):
            j = i
            while j < len(lines) and lines[j].startswith("|"):
                j += 1
            block = lines[i:j]
            head, sep, rows = block[0], block[1], block[2:]
            keep = [r for r in rows if RX_PTR.search(r)]
            drop = [r for r in rows if not RX_PTR.search(r)]
            if keep:
                out += [head, sep] + keep + [""]
            for r in drop:
                out.append("Base count, no locator needed: " + " · ".join(c.strip() for c in r.strip("|").split("|")) + ".")
                out.append("")
            i = j
        else:
            out.append(line)
            i += 1
    return "\n".join(out)


